package ru.team.pickup.model;

/**
 * CellSize — размер ячейки, enum.
 *
 * Каждый размер имеет числовой уровень: SMALL(1), MEDIUM(2), LARGE(3).
 * Чем больше уровень, тем крупнее ячейка.
 * Метод fits(CellSize required) проверяет, вмещает ли эта ячейка заказ требуемого размера.
 *
 * Не используем ordinal() для бизнес-логики, потому что ordinal зависит от
 * порядка объявления в enum — если кто-то добавит новый размер в середину,
 * числовые уровни сдвинутся и логика сломается. Поэтому задаём уровень явно.
 */
public enum CellSize {

    // SMALL — маленькая ячейка, уровень 1.
    // Конструктор enum вызывается неявно при объявлении.
    // SMALL(1) означает: передаём 1 в конструктор CellSize(int level).
    SMALL(1),

    // MEDIUM — средняя ячейка, уровень 2.
    MEDIUM(2),

    // LARGE — большая ячейка, уровень 3.
    LARGE(3);

    // Поле, хранящее числовой уровень размера.
    // final — значение задаётся один раз в конструкторе и не меняется.
    private final int level;

    // Конструктор enum. Вызывается автоматически при объявлении SMALL(1), MEDIUM(2), LARGE(3).
    // int level — числовой уровень, который определяет «вместимость» ячейки.
    CellSize(int level) {
        // this.level — поле текущего экземпляра enum.
        // level — параметр конструктора.
        this.level = level;
    }

    // Геттер для уровня. Нужен, чтобы внешний код мог сравнивать размеры численно.
    public int getLevel() {
        return level;
    }

    /**
     * Проверяет, вмещает ли эта ячейка заказ требуемого размера.
     * Ячейка вмещает заказ, если её уровень >= уровня требуемого размера.
     * Например, MEDIUM вмещает SMALL и MEDIUM, но не наоборот.
     *
     * @param required требуемый размер заказа
     * @return true, если ячейка подходит
     */
    public boolean fits(CellSize required) {
        // Сравниваем уровни: если уровень этой ячейки >= уровня требуемой — вмещает.
        // this.level — уровень текущей ячейки (например, 2 для MEDIUM).
        // required.level — уровень требуемого размера (например, 1 для SMALL).
        // 2 >= 1 → true: средняя ячейка вмещает маленький заказ.
        return this.level >= required.level;
    }
}
